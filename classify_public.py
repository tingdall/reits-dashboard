def match_type_word(name):
    for psub, kws in TYPE_WORDS:
        for k in kws:
            if k in name:
                return psub, f"名称含「{k}」"
    return None, None


def match_brand(name):
    for b, (psub, why) in BRAND.items():
        if b in name:
            return psub, f"资产实体：{b}（{why}）"
    return None, None


def main():
    snap = json.load(open(SNAP, encoding="utf-8"))
    items = snap.get("items") or []
    res = {}
    for x in items:
        name = x.get("name") or ""
        pt = x.get("ptype") or ""
        # 1) 资产类型词优先（最强证据）
        psub, why = match_type_word(name)
        conf = "high" if psub else None
        # 2) 品牌实体
        if not psub:
            psub, why = match_brand(name)
            conf = "high" if psub else "none"
        # 3) 大类兜底：商业不动产但无实体 → 待确认
        if not psub:
            psub, why, conf = "待确认", "未识别到资产实体，需人工核对", "none"
        res[str(x["id"])] = {"name": name, "ptype": pt, "psub": psub,
                             "evidence": why, "conf": conf}

    json.dump(res, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print(f"已分类 {len(res)} 个 → {OUT}")
    print("二级分类分布:", dict(Counter(v["psub"] for v in res.values()).most_common()))
    todo = [v for v in res.values() if v["psub"] == "待确认"]
    print(f"\n待确认 {len(todo)} 个：")
    for v in todo:
        print(f"  [{v['ptype']}] {v['name'][:40]}")


if __name__ == "__main__":
    main()
